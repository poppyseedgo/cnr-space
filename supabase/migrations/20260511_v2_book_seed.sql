-- 카테고리별 권수 (CSV 원본과 비교)
SELECT 
  bc.name AS 장르,
  bc.sort_order AS 정렬순서,
  count(b.id) AS 권수
FROM book_categories bc
LEFT JOIN books b ON b.category_id = bc.id
GROUP BY bc.id, bc.name, bc.sort_order
ORDER BY bc.sort_order;

-- 카테고리 없는 도서 (있으면 안 됨, 기대값: 0)
SELECT count(*) AS orphan_books
FROM books WHERE category_id IS NULL;

DO $$
DECLARE
  cat_count int;
  book_count int;
BEGIN
  SELECT count(*) INTO cat_count FROM book_categories;
  SELECT count(*) INTO book_count FROM books;
  
  IF cat_count != 14 THEN
    RAISE EXCEPTION '카테고리 수 불일치: 기대 14, 실제 %', cat_count;
  END IF;
  IF book_count != 299 THEN
    RAISE EXCEPTION '도서 수 불일치: 기대 299, 실제 %', book_count;
  END IF;
  
  RAISE NOTICE 'Seed 완료: % 카테고리, % 권', cat_count, book_count;
END $$;

COMMIT;



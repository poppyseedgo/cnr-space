-- 공지사항 페이지 백필 (2026-08-19 고지 지시)
--
-- 릴리즈 노트 이력에서 "전 직원이 체감하는 기능 오픈·정책 변경"만 선별해
-- 공지 이력으로 등록. 어드민 전용·핫픽스·내부 개편은 제외.
-- 기존 노쇼 제재 공지(8/4~8/31, 게시중)는 이미 있어 건드리지 않는다.
--
--  · 지난 공지 6건 — 당시 배포일 시작, 1~2주 게시했던 것으로 기간 설정
--  · 게시중 2건 — 자원예약 오픈 / 공지사항 페이지 신설 (오늘 ~ 8/26)
--    ⚠ 헤더 배너는 "최근 시작 1건"만 표시 → 자원예약을 1분 늦게 시작시켜
--      배너 = 자원예약, 페이지 게시중 목록 = 노쇼 + 2건 모두 노출
--  · 색 = 어드민 프리셋 값 그대로 (안내 #E6F2FF / 주의 #FEF3C7 / 강조 #111111)
--  · 기간 경계 = KST 자정/23:59:59 (기존 노쇼 공지와 동일 규칙)
--  · created_by NULL = 시스템 백필 (nullable 실측 확인)
--
-- 실행: SQL Editor 전체 붙여넣기 → Run. 재실행 안전(message 기준 중복 방지).
-- ============================================================================

INSERT INTO announcements (message, bg_color, text_color, starts_at, ends_at, is_active)
SELECT v.message, v.bg, v.fg, v.starts_at::timestamptz, v.ends_at::timestamptz, true
FROM (VALUES
  -- ── 지난 공지 (배포 당시 게시했던 것으로 백필) ──────────────────────────
  ('C&R SPACE가 정식 오픈했습니다. 회의실 예약은 이제 SPACE에서 진행해 주세요!',
   '#111111', '#FFFFFF', '2026-04-22T00:00:00+09:00', '2026-05-06T23:59:59+09:00'),

  ('도서관 서비스가 오픈했습니다. 사내 도서 검색과 대여 신청을 SPACE에서 이용해 보세요.',
   '#E6F2FF', '#1E1E1E', '2026-07-16T00:00:00+09:00', '2026-07-23T23:59:59+09:00'),

  ('ZOOM 서비스 종료에 따라 SPACE의 ZOOM 예약 기능이 종료되었습니다. 기존 예약은 회의실 예약으로 유지됩니다.',
   '#FEF3C7', '#92400E', '2026-07-21T00:00:00+09:00', '2026-07-28T23:59:59+09:00'),

  ('도서 대여가 신청 → 관리자 승인 방식으로 변경되었습니다. 승인 결과는 메일과 알림으로 안내됩니다.',
   '#E6F2FF', '#1E1E1E', '2026-07-22T00:00:00+09:00', '2026-07-29T23:59:59+09:00'),

  ('회의실 예약 화면이 개편되었습니다 — 회의 목적 선택이 추가되고, 모바일 예약 화면이 전면 개선되었습니다.',
   '#E6F2FF', '#1E1E1E', '2026-07-27T00:00:00+09:00', '2026-08-03T23:59:59+09:00'),

  ('예약 달력에 법정 공휴일과 회사 이벤트가 표시됩니다. 대체·임시공휴일도 자동 반영됩니다.',
   '#E6F2FF', '#1E1E1E', '2026-08-03T00:00:00+09:00', '2026-08-10T23:59:59+09:00'),

  -- ── 게시중 (오늘 ~ 8/26) — 자원예약이 1분 늦게 시작 = 헤더 배너 차지 ──
  ('공지사항 페이지가 열렸습니다. 메뉴에서 지난 공지 이력을 확인할 수 있어요. 메뉴 순서도 새로 정리되었습니다.',
   '#E6F2FF', '#1E1E1E', '2026-08-19T00:00:00+09:00', '2026-08-26T23:59:59+09:00'),

  ('자원예약 서비스가 오픈했습니다! 레이저 포인터 등 공용 자원을 메뉴 > 자원예약에서 예약해 보세요.',
   '#111111', '#FFFFFF', '2026-08-19T00:01:00+09:00', '2026-08-26T23:59:59+09:00')
) AS v(message, bg, fg, starts_at, ends_at)
WHERE NOT EXISTS (SELECT 1 FROM announcements a WHERE a.message = v.message);

-- ── 검증 — 전체 공지 시간순 (기존 노쇼 포함 9건 기대) ────────────────────
SELECT to_char(starts_at AT TIME ZONE 'Asia/Seoul', 'MM/DD') AS 시작,
       to_char(ends_at   AT TIME ZONE 'Asia/Seoul', 'MM/DD') AS 종료,
       CASE WHEN is_active AND now() BETWEEN starts_at AND ends_at
            THEN '게시중' ELSE '지난 공지' END AS 상태,
       left(message, 40) AS 내용
FROM announcements ORDER BY starts_at;
